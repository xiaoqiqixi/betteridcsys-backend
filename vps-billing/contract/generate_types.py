"""Generate response DTOs from the pinned contract; no network access."""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parent
document = json.loads((ROOT / 'openapi.json').read_text())
schemas = document['components']['schemas']
initialisms = {'id':'ID','ids':'IDs','cpu':'CPU','ip':'IP','ipv4':'IPv4','ipv6':'IPv6','os':'OS','url':'URL','sha256':'SHA256','ssh':'SSH','api':'API','mb':'MB','gb':'GB','bps':'BPS','smtp':'SMTP','csrf':'CSRF'}
def field(s):
    return ''.join(initialisms.get(x,x[:1].upper()+x[1:]) for x in s.split('_'))
def typ(s, indent=''):
    if '$ref' in s: return s['$ref'].rsplit('/',1)[1]
    if 'anyOf' in s:
        other=[x for x in s['anyOf'] if x.get('type')!='null']
        if len(other)==1 and len(other)!=len(s['anyOf']): return '*'+typ(other[0],indent)
        return 'any'
    if 'oneOf' in s: return 'any'
    t=s.get('type')
    if isinstance(t,list): return '*'+typ(dict(s,type=next(x for x in t if x!='null')),indent)
    if t=='string': return 'string'
    if t=='integer': return 'int64'
    if t=='number': return 'float64'
    if t=='boolean': return 'bool'
    if t=='array': return '[]'+typ(s['items'],indent)
    if t=='object':
        if 'properties' not in s: return 'map[string]'+typ(s.get('additionalProperties',{}),indent)
        out=['struct {']
        for k,v in s['properties'].items():
            omit='' if k in s.get('required',[]) else ',omitempty'
            out.append(indent+'\t'+field(k)+' '+typ(v,indent+'\t')+' `json:"'+k+omit+'"`')
        out.append(indent+'}')
        return '\n'.join(out)
    return 'any'
text='// Code generated by vps-billing/contract/generate_types.py; DO NOT EDIT.\n\npackage financeapi\n\n'
for name,schema in schemas.items(): text+='type '+name+' = '+typ(schema)+'\n\n'
for path, methods in document['paths'].items():
    for method, op in methods.items():
        name=op['operationId'][:1].upper()+op['operationId'][1:]
        if 'requestBody' in op:
            text+='type '+name+'Input = '+typ(op['requestBody']['content']['application/json']['schema'])+'\n\n'
        text+='type '+name+'Response = '+typ(op['responses']['200']['content']['application/json']['schema']['properties']['data'])+'\n\n'
(ROOT.parent/'backend/internal/financeapi/types.go').write_text(text)
validation={'components':{'schemas':schemas},'requests':{}}
for methods in document['paths'].values():
    for op in methods.values():
        if 'requestBody' in op: validation['requests'][op['operationId']]=op['requestBody']['content']['application/json']['schema']
encoded=json.dumps(validation,ensure_ascii=True,separators=(',',':'))
(ROOT.parent/'backend/internal/financeapi/schemas.go').write_text('// Code generated by vps-billing/contract/generate_types.py; DO NOT EDIT.\npackage financeapi\n\nconst validationDocument = '+json.dumps(encoded)+'\n')
